"use strict";

const byId = (id) => document.getElementById(id);
const token = byId("token");
const run = byId("run");
const probe = byId("probe");
const releaseGoal = byId("release-goal");
let report;
let liveAccess = "unavailable";
const fixtureNames = {
  synthetic: "Synthetic sensors (FP32 reference)",
  clean: "Optical Digits original split (FP16 reference)",
  injected_overlap: "Optical Digits with an injected overlap",
};

async function loadLiveAccess() {
  try {
    const response = await fetch("/healthz");
    if (!response.ok) throw new Error("Health check failed.");
    const health = await response.json();
    liveAccess = health.live_access || "unavailable";
    byId("containment").hidden = health.local_preview;
  } catch {
    byId("status").textContent = "Could not reach QuantGate. Reload the page to retry.";
    return;
  }
  const live = liveAccess !== "unavailable";
  byId("prompt-field").hidden = !live;
  releaseGoal.required = live;
  token.required = liveAccess === "token";
  byId("token-field").hidden = !token.required;
  run.textContent = live ? "Run evaluation" : "Run bundled example";
  run.disabled = false;
}

loadLiveAccess();

async function request(path, body, accessToken) {
  const headers = { "Content-Type": "application/json" };
  if (accessToken) headers["X-Demo-Token"] = accessToken;
  const response = await fetch(path, { method: "POST", headers, body: JSON.stringify(body) });
  const data = await response.json();
  if (!response.ok) throw new Error(data.error || "Request failed.");
  return data;
}

function setBusy(busy) {
  run.disabled = busy;
  probe.disabled = busy;
  releaseGoal.disabled = busy;
  token.disabled = busy;
}

function describeContract(contract) {
  return `${fixtureNames[contract.fixture]} · ${contract.budget_bytes} bytes/sample · max loss ${contract.max_drop_bps / 100} percentage points`;
}

function showReport(data) {
  report = data;
  const approved = data.decision === "approve";
  const origin = {
    live: "VULTR GENERATED",
    example: "SANDBOXED EXAMPLE",
    local: "LOCAL PREVIEW",
  }[data.mode];
  const labels = {
    split_overlap: "A sample occurs in more than one partition. Release blocked.",
    budget_below_minimum: `Even INT8 needs ${data.minimum_bytes} bytes/sample. The budget is ${data.budget_bytes}.`,
    no_candidate_passed_development: "No configuration met the contract on development.",
    holdout_accuracy_failed: "The selected configuration exceeded the accuracy loss allowed on holdout.",
    holdout_passed: `${data.selected_format?.toUpperCase() || data.selected_bits?.map((bits) => bits === 8 ? "INT8" : "FP16").join(" / ")} met the release contract.`,
  };
  byId("verification").textContent =
    `${approved ? "APPROVED" : "BLOCKED"} · ${data.reference_verified ? origin : "PREFLIGHT"}`;
  byId("verification").dataset.verdict = data.decision;
  byId("recommendation").textContent = labels[data.reason];
  byId("plan-contract").textContent = describeContract(data);
  const conflict = data.split.conflicts[0];
  byId("split-evidence").textContent = conflict
    ? `${conflict.first_split} ${conflict.first_sample} matches ${conflict.second_split} ${conflict.second_sample}.`
    : "No exact pixel matches across training, calibration, development and holdout.";
  byId("explanation-section").hidden = data.mode !== "live";
  byId("explanation").textContent = data.explanation || "Vultr's explanation is unavailable for this run. The measured decision is shown above.";
  byId("measurements").hidden = !data.reference_verified;
  byId("holdout").hidden = !data.holdout || Boolean(data.precision_comparison);
  byId("precision-comparison").hidden = !data.precision_comparison;
  const kernel = byId("kernel");
  kernel.hidden = !data.source;
  kernel.open = Boolean(data.source) && data.mode === "live";
  byId("kernel-title").textContent = data.mode === "live"
    ? "Python generated by Vultr Inference for this run"
    : "Bundled Python scoring kernel";
  if (data.reference_verified) showMeasurements(data);
  byId("trace").replaceChildren(...data.trace.map((event) => {
    const item = document.createElement("li");
    item.textContent = event;
    return item;
  }));
  byId("source").textContent = data.source || "";
  byId("report").hidden = false;
}

function showMeasurements(data) {
  const selected = data.attempts.find((attempt) => attempt.result === "selected");
  const baseline = (data.baseline_format || "fp16").toUpperCase();
  const baselineBytes = data.baseline_encoded_bytes ?? data.fp16_encoded_bytes;
  byId("comparison").textContent = selected
    ? `Candidate ${selected.format ? selected.format.toUpperCase() + " · " : ""}${selected.encoded_bytes} B/sample · ${baseline} ${baselineBytes} B/sample · budget ${data.budget_bytes} B/sample`
    : `Budget ${data.budget_bytes} B/sample · maximum drop ${data.max_drop_bps / 100} percentage points`;
  const ms = data.timing_ms;
  byId("timings").textContent =
    `${data.verified_threshold_count} thresholds verified · native sweeps ${ms.native_sweep.toFixed(2)} ms · Python reference ${ms.python_reference_sweep.toFixed(2)} ms · compile ${ms.compile.toFixed(0)} ms · inference ${ms.inference.toFixed(0)} ms · workflow ${ms.workflow.toFixed(0)} ms`;
  if (data.precision_comparison) {
    const scores = data.precision_comparison;
    byId("precision-rows").replaceChildren(...Object.entries(scores).map(([name, format]) => {
      const row = document.createElement("tr");
      row.insertCell().textContent = name.toUpperCase();
      row.insertCell().textContent = format.encoded_bytes;
      for (const [slice, score] of Object.entries(format.holdout)) {
        const accuracy = 100 * score.correct / score.total;
        const delta = 100 * (score.correct - scores.fp32.holdout[slice].correct) / score.total;
        row.insertCell().textContent = `${accuracy.toFixed(2)}% (${delta > 0 ? "+" : ""}${delta.toFixed(2)} pp)`;
      }
      return row;
    }));
    return;
  }
  const slices = { clean: "Original", shift_left: "One cell left", shift_right: "One cell right" };
  byId("rows").replaceChildren(...Object.entries(data.holdout?.candidate || {}).map(([name, candidate]) => {
    const baseline = data.holdout.fp16[name];
    const row = document.createElement("tr");
    for (const value of [slices[name], `${candidate.correct}/${candidate.total}`, `${baseline.correct}/${baseline.total}`]) {
      row.insertCell().textContent = value;
    }
    return row;
  }));
}

byId("prompt-form").addEventListener("submit", async (event) => {
  event.preventDefault();
  if (run.disabled) return;
  const status = byId("status");
  byId("report").hidden = true;
  const live = liveAccess !== "unavailable";
  const accessToken = token.value;
  setBusy(true);
  try {
    let contract = {fixture: "synthetic", budget_bytes: 96, max_drop_bps: 50};
    if (live) {
      status.textContent = "Planning the evaluation…";
      contract = await request("/api/plan", {prompt: releaseGoal.value}, accessToken);
      if (contract.unsupported) {
        status.textContent = "Try specifying a dataset, byte budget or accuracy limit for the release.";
        return;
      }
    }
    status.textContent = `Running evaluation… ${describeContract(contract)}`;
    const data = await request("/api/release", {...contract, mode: live ? "live" : "example"}, accessToken);
    showReport(data);
    status.textContent = "Release evaluation completed.";
  } catch (error) {
    status.textContent = error.message;
  } finally {
    setBusy(false);
  }
});

probe.addEventListener("click", async () => {
  const status = byId("probe-status");
  setBusy(true);
  status.textContent = "Starting disposable worker…";
  try {
    const data = await request("/api/containment", {});
    status.textContent = `Worker started, exceeded the ${data.limit_seconds}s deadline, and was removed.`;
  } catch (error) {
    status.textContent = error.message;
  } finally {
    setBusy(false);
  }
});

byId("download").addEventListener("click", () => {
  const url = URL.createObjectURL(new Blob([JSON.stringify(report, null, 2)], { type: "application/json" }));
  const link = document.createElement("a");
  link.href = url;
  link.download = "quantgate-release-report.json";
  link.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
});
